/// One hand-authored session: a persona, a timeline and the two questions it
/// is graded on.
///
/// Every field is a literal somebody wrote and can argue with. The expansion
/// in [`generate`] adds nothing that is not derivable from these fields plus
/// the filler pool, which is what makes regeneration byte-identical.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Seed {
    pub id: &'static str,
    /// Which of the six memory abilities this session belongs to. Five seeds
    /// each; `every_memory_ability_has_at_least_five_sessions` is the guard.
    pub ability: &'static str,
    /// "cs" or "en". Both, for `paraphrase.rs`'s reason: this deployment's
    /// traffic is Czech and Czech inflects the tokens a lexical index keys on.
    pub lang: &'static str,
    pub persona: &'static str,
    /// Turn 1. Said once and never written as a fact, so the only route from
    /// it to turn 11 is the rolling summary.
    pub opening: &'static str,
    /// A word of `opening` that appears nowhere else in the session — the
    /// token the summary condition looks for.
    pub mark: &'static str,
    /// Turn 2: the sentence `ask` paraphrases, and the fact it writes.
    pub said: &'static str,
    pub key: &'static str,
    pub value: &'static str,
    /// Turn 3: the same key with a new value. The graded answer is the new
    /// one; the old one is legitimate material only behind the `(was …)`
    /// marker.
    pub updated: &'static str,
    pub update_new: &'static str,
    /// Turn 11, in different words from `said` — graded by
    /// `every_graded_question_is_a_paraphrase`.
    pub ask: &'static str,
    /// The session's own `reply`-scoped note, beside the ability's.
    pub note: &'static str,
    /// Turn 12: a question this session never held an answer to.
    pub unanswerable: &'static str,
    /// A span of `unanswerable` whose tokens appear nowhere in the session,
    /// so `recall` can only report "no matches".
    pub recall_query: &'static str,
    /// What a reply that did not decline would have to invent.
    pub invented: &'static str,
    /// A first draft that states it, so the grounding interceptor — harness,
    /// not model — is what the abstention arm grades.
    pub invented_draft: &'static str,
}

/// The six memory abilities, in the order [`crate::eval::run_all_for`]
/// reports them. Written down so the ability column of this table and the
/// ability column of that one cannot drift apart.
pub const MEMORY_ABILITIES: [&str; 6] = [
    "information extraction",
    "multi-session reasoning",
    "temporal reasoning",
    "knowledge updates",
    "abstention",
    "selective forgetting",
];

/// The note every session carries at `global` scope: it reaches the emitter,
/// which is the half of the engine `guidance_notes_for` serves.
pub const GLOBAL_NOTE: &str = "Prefer a stored fact over asking the user again.";

/// One `reply`-scoped note per ability, the thing that ability's graded turn
/// is supposed to act on.
pub fn ability_note(ability: &str) -> &'static str {
    match ability {
        "information extraction" => "Answer from the stored facts, not from the transcript.",
        "multi-session reasoning" => "A fact stated in another conversation still counts.",
        "temporal reasoning" => "When a value changed, give the current one and name the old one.",
        "knowledge updates" => "Only the newest value of a key is true.",
        "abstention" => "If the context does not carry it, say you do not know.",
        _ => "A forgotten value is gone; do not reconstruct it.",
    }
}

/// Filler, one pool per language. Deliberately contentless: its whole job is
/// to push turns 1–3 out of the six-turn window, and a filler line that said
/// anything would become a second source for the graded answer.
const EN_FILLER: [&str; 8] = [
    "what else can you do",
    "never mind that",
    "tell me something",
    "still there?",
    "good",
    "carry on",
    "one more thing",
    "right",
];

const CS_FILLER: [&str; 8] = [
    "co ještě umíš",
    "to nech být",
    "řekni mi něco",
    "jsi tam?",
    "dobře",
    "pokračuj",
    "ještě něco",
    "tak jo",
];

/// Seven filler lines for the `n`th seed, rotated through the pool so two
/// sessions do not read identically. A pure function of `(lang, n)`, which is
/// what keeps regeneration byte-identical.
fn filler(lang: &str, n: usize) -> Vec<&'static str> {
    let pool: &[&'static str; 8] = if lang == "cs" { &CS_FILLER } else { &EN_FILLER };
    (0..7).map(|i| pool[(n + i) % pool.len()]).collect()
}

/// "forget this" and "and now?", per language — the two extra turns the
/// selective-forgetting seeds take.
fn forget_turns(lang: &str) -> (&'static str, &'static str) {
    if lang == "cs" {
        ("zapomeň to prosím", "a co to bylo?")
    } else {
        ("please forget that", "and what was it?")
    }
}

/// The one line the multi-session seeds say in a second session.
fn second_session_ask(lang: &str) -> &'static str {
    if lang == "cs" {
        "připomeň mi to ještě jednou"
    } else {
        "remind me of that once more"
    }
}

