/// What a turn is for, so the runner and the renderer read the same plan
/// instead of each counting turns for themselves.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Role {
    /// Turns 1–3 and the filler: they build the state, they are not graded.
    Setup,
    /// Turn 11 — the paraphrased question the answerable arm grades.
    Graded,
    /// Turn 12 — the unanswerable one, graded in its own arm.
    Abstain,
    /// Selective forgetting: the request, then the question after it.
    Forget,
    Recheck,
    /// Multi-session: the same question in a second session.
    Across,
}

/// One turn of a generated session.
#[derive(Debug, Clone, PartialEq)]
pub struct Turn {
    pub text: String,
    pub script: Vec<Proposal>,
    pub role: Role,
    /// `false` for the session the seed is about, `true` for the second one
    /// the multi-session seeds open.
    pub second_session: bool,
    /// The inventing first draft, on the abstention turn only.
    pub first_draft: Option<&'static str>,
}

/// A seed expanded into the turns a harness can run.
#[derive(Debug, Clone, PartialEq)]
pub struct Session {
    pub seed: Seed,
    pub notes: Vec<Note>,
    pub turns: Vec<Turn>,
}

impl Session {
    /// Notes the reply model can be shown — the `reply`-scoped ones, which
    /// is what `guidance_notes_for_reply` filters to.
    pub fn reply_notes(&self) -> Vec<&str> {
        self.notes
            .iter()
            .filter(|n| n.scope == "reply")
            .map(|n| n.text.as_str())
            .collect()
    }

    pub fn rules(&self) -> LearnedRules {
        LearnedRules {
            notes: self.notes.clone(),
            ..LearnedRules::default()
        }
    }
}

fn plain(text: &str, role: Role) -> Turn {
    Turn {
        text: text.to_string(),
        script: vec![],
        role,
        second_session: false,
        first_draft: None,
    }
}

/// Expand every seed. Pure: same seeds and the same filler pool in, the same
/// `Vec<Session>` out, which is the whole of what
/// `fixtures_regenerate_byte_identically` checks.
pub fn generate() -> Vec<Session> {
    seeds()
        .iter()
        .enumerate()
        .map(|(n, seed)| {
            let mut turns = vec![
                plain(seed.opening, Role::Setup),
                Turn {
                    script: vec![remember(seed.key, seed.value)],
                    ..plain(seed.said, Role::Setup)
                },
                Turn {
                    script: vec![remember(seed.key, seed.update_new)],
                    ..plain(seed.updated, Role::Setup)
                },
            ];
            turns.extend(
                filler(seed.lang, n)
                    .into_iter()
                    .map(|t| plain(t, Role::Setup)),
            );
            turns.push(plain(seed.ask, Role::Graded));
            turns.push(Turn {
                script: vec![recall_for(seed.recall_query)],
                first_draft: Some(seed.invented_draft),
                ..plain(seed.unanswerable, Role::Abstain)
            });
            match seed.ability {
                "selective forgetting" => {
                    let (drop, again) = forget_turns(seed.lang);
                    turns.push(Turn {
                        script: vec![crate::eval::forget(seed.key)],
                        ..plain(drop, Role::Forget)
                    });
                    turns.push(plain(again, Role::Recheck));
                }
                "multi-session reasoning" => turns.push(Turn {
                    second_session: true,
                    ..plain(second_session_ask(seed.lang), Role::Across)
                }),
                _ => {}
            }
            Session {
                seed: *seed,
                notes: vec![
                    Note::new("reply", ability_note(seed.ability), 0.0),
                    Note::new("reply", seed.note, 0.0),
                    Note::new("global", GLOBAL_NOTE, 0.0),
                ],
                turns,
            }
        })
        .collect()
}

/// The whole corpus as one document, byte for byte.
///
/// The regeneration test needs something to compare, and comparing
/// `Vec<Session>` by `PartialEq` would pass on two structurally equal values
/// whose *rendering* differed — and the rendering is what a person reviews.
/// So the test compares this.
pub fn render_corpus() -> String {
    let mut out = String::from("M10 T5.1 — scripted sessions from hand-authored seeds\n");
    for s in generate() {
        out.push_str(&format!(
            "\n=== {} [{} · {}] ===\npersona: {}\n",
            s.seed.id, s.seed.ability, s.seed.lang, s.seed.persona
        ));
        for n in &s.notes {
            out.push_str(&format!("note[{}] {} {}\n", n.scope, n.hash, n.text));
        }
        for (i, t) in s.turns.iter().enumerate() {
            out.push_str(&format!(
                "{:>3} {:?}{} {}\n",
                i + 1,
                t.role,
                if t.second_session { " (session B)" } else { "" },
                t.text
            ));
            for p in &t.script {
                out.push_str(&format!("      -> {} {}\n", p.action, p.args));
            }
            if let Some(d) = t.first_draft {
                out.push_str(&format!("      ~~ first draft: {d}\n"));
            }
        }
    }
    out
}

