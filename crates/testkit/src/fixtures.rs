//! M10 T5.1 — the scripted sessions every M9 knob was waiting for.
//!
//! M9 shipped five knobs at their defaults and could not read four of them,
//! for one reason: *the scripted suite carries no summary and no notes*. Its
//! §Results T0.4 says so in the only way that matters — `--ablate summary`
//! and `--ablate guidance` both reported **9/9 → 9/9**, a zero that means
//! "nothing to see" rather than "nothing there". A blind instrument and an
//! insensitive one print the same number.
//!
//! So this module builds sessions that demonstrably carry both, out of
//! **hand-authored seeds**. Not a generator model: the plan's own risk line
//! is *"fixtures generated by a model leak the model's style"*, and the
//! answer it wrote down is a seed a person can read, a deterministic
//! expansion, and a byte-identical regeneration ([`render_corpus`], graded by
//! `fixtures_regenerate_byte_identically`).
//!
//! # What one session carries
//!
//! Every seed expands to the same twelve-turn shape, because the shape is
//! what makes the ablation arms readable — a suite whose fixtures carried a
//! summary *sometimes* would produce a delta nobody could attribute.
//!
//! | turn | what happens | which exit criterion it serves |
//! |---|---|---|
//! | 1 | the **opening**: said once, never remembered as a fact | (a) only the rolling summary can carry its `mark` into turn 11 |
//! | 2 | the durable statement → `remember_fact` | (d) the graded question paraphrases *this* sentence |
//! | 3 | the same key **restated with a new value** | (c) LongMemEval's knowledge update; graded on the new value |
//! | 4–10 | filler, which pushes turns 1–3 out of the six-turn window | the window cannot be the source of the answer |
//! | 11 | the graded question — a paraphrase, cs or en | (d) |
//! | 12 | a question about something the session never held | (e) abstention, scored in its own arm |
//!
//! `maybe_summarize` runs after every turn, exactly where `dispatch.rs` runs
//! it on the live path. With `window_turns = 6` and `summary_every_turns = 4`
//! that fires once, after turn 10, over turns 1–4 — so turn 11's reply
//! context carries a real `Summarized` event built by the engine's own
//! summarizer path, and the `mark` from turn 1 is in the prompt through the
//! summary block and through nothing else.
//!
//! Notes arrive the way the live engine gets them, through
//! [`nscore::LearnedRules`] on `EngineConfig.learned`. **Two of them are
//! scoped `reply`, one `global`**, and that split is not decoration:
//! `guidance_notes_for_reply` (`crates/core/src/learned.rs`) renders only
//! `reply`-scoped notes into the reply context, and the graded turn is a
//! reply turn. A fixture that handed the engine two `global` notes and then
//! graded the reply prompt would have been blind in a new way.
//!
//! # Why abstention is a separate arm
//!
//! 2606.09376: precision-only scoring rewards a model that answers nothing.
//! If the unanswerable items were folded into one pass rate, a harness that
//! declined every question would climb it. So [`Fixture`] carries `passed`
//! and `declined` as two verdicts over two turns, [`render_table`] prints
//! two totals, and neither can be bought with the other.
//!
//! # What the table prints that the M9 one could not
//!
//! `summary` and `notes` per fixture, read off the **store and the rules**
//! rather than off the graded context. Under `--ablate summary` the block is
//! blanked after the fit, so the graded turn sees none — but the session
//! still holds its `Summarized` event, and the column says so. That is the
//! difference between blind and insensitive, printed rather than argued.

use crate::eval::{recall_for, remember, require, Harness, Run, Shown};
use nscore::{EventKind, FactState, LearnedRules, MemoryStore, Note, Proposal, SessionId};

