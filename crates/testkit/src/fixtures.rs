/// One graded session: two verdicts, and the two counts that make a zero
/// delta readable.
#[derive(Debug, Clone, PartialEq)]
pub struct Fixture {
    pub id: &'static str,
    pub ability: &'static str,
    pub lang: &'static str,
    /// The answerable turn.
    pub passed: bool,
    /// The unanswerable one, in its own arm.
    pub declined: bool,
    pub turns: usize,
    pub requests: usize,
    /// Replier calls alone, both sessions of this fixture (M10 T5.4, arm 3).
    ///
    /// Split out of `requests` because the obligation interceptor's whole
    /// cost is a *second* replier call on a turn that already had one: an
    /// arm reported on `requests` would hide that regeneration among the
    /// emitter's proposals, which the knob does not touch.
    pub replier_requests: usize,
    pub prompt_chars: usize,
    /// Characters of `Summarized` this session **holds**, read off the event
    /// log. Non-zero even under `--ablate summary`, which is the point: a
    /// suite that reported zero here would be blind, and one that reported a
    /// number here and no delta is insensitive.
    pub summary_chars: usize,
    /// Characters of summary the graded turn was **shown**. Zero under
    /// `--ablate summary`.
    pub summary_shown: usize,
    /// `reply`-scoped notes handed to the engine, and the ones the graded
    /// context carried. Same pair of readings, same reason.
    pub notes_held: usize,
    pub notes_shown: usize,
    /// `ReplyEchoed` events this fixture's two sessions hold (M12 T4.4b).
    ///
    /// Reported per arm because the act-or-answer arm is the first one that
    /// changes *who writes the reply*: the double's fixed marker cannot echo
    /// its own prompt, and a model's answer can. A column that stays zero on
    /// both arms says the monitor saw nothing, not that nothing was there.
    pub echoed: usize,
    pub detail: String,
    pub abstain_detail: String,
}

/// `ReplyEchoed` events these sessions hold (M12 T4.4b).
async fn echoed_in(h: &Harness, sids: &[&SessionId]) -> usize {
    let mut n = 0;
    for sid in sids {
        n += h
            .store()
            .load(sid)
            .await
            .unwrap_or_default()
            .iter()
            .filter(|e| matches!(e.kind, EventKind::ReplyEchoed { .. }))
            .count();
    }
    n
}

/// The engine's own summary for this session, as the log holds it.
async fn summary_chars_of(h: &Harness, sid: &SessionId) -> usize {
    h.store()
        .load(sid)
        .await
        .unwrap_or_default()
        .iter()
        .filter_map(|e| match &e.kind {
            EventKind::Summarized { summary } => {
                Some(nscore::render_summary(summary).chars().count())
            }
            _ => None,
        })
        // The newest summary, found from the back: `last()` walked every
        // event in the session to arrive at the same one.
        .next_back()
        .unwrap_or(0)
}

/// Run one session and grade both of its arms.
pub async fn run_one(session: &Session, run: Run) -> Fixture {
    let seed = session.seed;
    let h = Harness::for_fixture(run, session.rules(), seed.persona);
    let a = SessionId(format!("fx-{}-a", seed.id.replace('/', "-")));
    let b = SessionId(format!("fx-{}-b", seed.id.replace('/', "-")));

    let mut graded: Option<Shown> = None;
    let mut abstain: Vec<Shown> = Vec::new();
    let mut recheck: Option<Shown> = None;
    let mut across: Option<Shown> = None;
    // Every version of the graded key **as the graded turn left it**. Read
    // inside the loop, not after it: the selective-forgetting seeds go on to
    // delete the key, and a history read at the end would grade the update
    // against a store the forget had already emptied.
    let mut history = Vec::new();
    for t in &session.turns {
        let sid = if t.second_session { &b } else { &a };
        let shown = h
            .turn_drafting(sid, &t.text, t.script.clone(), t.first_draft)
            .await;
        match t.role {
            Role::Graded => {
                graded = shown.first().cloned();
                history = h
                    .store()
                    .fact_history("global", seed.key)
                    .await
                    .unwrap_or_default();
            }
            Role::Abstain => abstain = shown,
            Role::Recheck => recheck = shown.first().cloned(),
            Role::Across => across = shown.first().cloned(),
            _ => {}
        }
    }
    let c = h.counters().await;
    let g = graded.clone().unwrap_or_default();
    let reply_notes = session.reply_notes();

    // ---- the answerable arm -------------------------------------------
    let mut fails = Vec::new();
    // (a) the summary. Three conditions, because "the value is in the
    // prompt" alone would pass on a window that never rolled.
    require(&mut fails, g.summary.is_some(), || {
        "the graded turn was shown no summary block".into()
    });
    require(&mut fails, g.prompt.contains(seed.mark), || {
        format!(
            "{:?} reached no block of the graded prompt; only the summary could carry it",
            seed.mark
        )
    });
    require(&mut fails, !g.window.contains(seed.mark), || {
        format!(
            "turn 1 is still in the window, so {:?} proves nothing",
            seed.mark
        )
    });
    // (b) the notes.
    for note in &reply_notes {
        require(&mut fails, g.guidance.iter().any(|r| r == note), || {
            format!("the reply context did not carry the note {note:?}")
        });
    }
    // (c) the knowledge update, on both sides: the store holds one current
    // version and the context shows its value, not the one it replaced.
    let current: Vec<_> = history
        .iter()
        .filter(|f| f.state == FactState::Current)
        .collect();
    require(&mut fails, current.len() == 1, || {
        format!("{} current rows for {}, want 1", current.len(), seed.key)
    });
    require(&mut fails, g.rows_for(seed.key) == 1, || {
        format!(
            "{} {} lines in the context — ghost mixing: {:?}",
            g.rows_for(seed.key),
            seed.key,
            g.facts
        )
    });
    // (d) the paraphrase. The question is asked in different words and the
    // answer still reached the model — through the fact block, not through a
    // transcript that no longer holds it.
    match g.fact_line(seed.key) {
        Some(line) => require(&mut fails, line.contains(seed.update_new), || {
            format!("{} shown as {line:?}, not {:?}", seed.key, seed.update_new)
        }),
        None => fails.push(format!("{} was not in the reply context", seed.key)),
    }
    require(&mut fails, !g.window.contains(seed.update_new), || {
        "the restated value is still in the window; this says nothing about memory".into()
    });
    // Per-ability condition.
    match seed.ability {
        "information extraction" => require(&mut fails, c.recall_calls == 1, || {
            format!(
                "{} recall calls; only the abstention turn should search",
                c.recall_calls
            )
        }),
        "multi-session reasoning" => match &across {
            Some(s) => {
                require(&mut fails, s.window.is_empty(), || {
                    format!("session two already had a window: {:?}", s.window)
                });
                require(
                    &mut fails,
                    s.fact_line(seed.key)
                        .map(|l| l.contains(seed.update_new))
                        .unwrap_or(false),
                    || format!("the fact did not cross into session two: {:?}", s.facts),
                );
            }
            None => fails.push("the second session never reached the reply model".into()),
        },
        "temporal reasoning" => {
            let want = format!(
                "{}: \"{}\" (was \"{}\" until ",
                seed.key, seed.update_new, seed.value
            );
            require(
                &mut fails,
                g.fact_line(seed.key)
                    .map(|l| l.starts_with(&want))
                    .unwrap_or(false),
                || format!("superseded value not rendered: {:?}", g.fact_line(seed.key)),
            );
        }
        "knowledge updates" => {
            let superseded: Vec<_> = history
                .iter()
                .filter(|f| f.state == FactState::Superseded)
                .collect();
            require(
                &mut fails,
                superseded.len() == 1 && superseded[0].valid_to.is_some(),
                || {
                    format!(
                        "{} superseded rows with a valid_to, want 1",
                        superseded.len()
                    )
                },
            );
        }
        "selective forgetting" => match &recheck {
            Some(s) => {
                require(&mut fails, s.fact_line(seed.key).is_none(), || {
                    format!("{} survived the forget: {:?}", seed.key, s.facts)
                });
                let after = h
                    .store()
                    .fact_history("global", seed.key)
                    .await
                    .unwrap_or_default();
                require(
                    &mut fails,
                    !after.iter().any(|f| f.state == FactState::Current),
                    || "the store still holds a current version after forget_fact".into(),
                );
            }
            None => fails.push("the turn after the forget never reached the reply model".into()),
        },
        // "abstention": its condition is the arm below, graded separately so
        // a declined answer can never be scored as a correct one.
        _ => {}
    }

    // ---- the abstention arm -------------------------------------------
    let mut declines = Vec::new();
    let first = abstain.first().cloned().unwrap_or_default();
    require(&mut declines, c.recall_calls == 1, || {
        format!(
            "{} recall calls, want the one the unanswerable turn makes",
            c.recall_calls
        )
    });
    require(&mut declines, c.recall_hits == 0, || {
        format!(
            "recall returned {} hits for something never said",
            c.recall_hits
        )
    });
    require(&mut declines, first.trace.contains("no matches"), || {
        format!(
            "the reply model was not told the search found nothing: {:?}",
            first.trace
        )
    });
    require(&mut declines, !first.shows(seed.invented), || {
        format!(
            "the context already carried {:?}; abstention is untestable here",
            seed.invented
        )
    });
    require(&mut declines, c.flags == 1, || {
        format!(
            "{} interceptor flags, want 1 for the invented value",
            c.flags
        )
    });
    require(&mut declines, abstain.len() == 2, || {
        format!(
            "{} drafts; the flagged reply was not regenerated",
            abstain.len()
        )
    });
    if let Some(second) = abstain.get(1) {
        require(
            &mut declines,
            second.do_not_state.iter().any(|s| s == seed.invented),
            || {
                format!(
                    "the regeneration was not told what to drop: {:?}",
                    second.do_not_state
                )
            },
        );
    }

    Fixture {
        id: seed.id,
        ability: seed.ability,
        lang: seed.lang,
        passed: fails.is_empty(),
        declined: declines.is_empty(),
        turns: c.turns,
        requests: c.emitter_calls + h.reply_calls(),
        replier_requests: h.reply_calls(),
        prompt_chars: g.chars(),
        summary_chars: summary_chars_of(&h, &a).await,
        summary_shown: g.summary.as_ref().map(|s| s.chars().count()).unwrap_or(0),
        notes_held: reply_notes.len(),
        notes_shown: g.guidance.len(),
        echoed: echoed_in(&h, &[&a, &b]).await,
        detail: fails.join("; "),
        abstain_detail: declines.join("; "),
    }
}

/// Every session, in seed order.
///
/// Sequential for [`crate::eval::run_all_for`]'s reason: each session builds
/// its own store and engines, so they are independent, but `requests` is a
/// reported column and a concurrent run would let the scheduler into it.
pub async fn run_all_for(run: Run) -> Vec<Fixture> {
    let mut out = Vec::new();
    for s in generate() {
        out.push(run_one(&s, run).await);
    }
    out
}

